"""E2 probe GENERATOR, drafts exact-value questions FROM judge-kept reference chunks.

Flow: pick keep>=4 reference docs (v1: single-chunk docs only, so chunk text == doc text,
no chunker duplication; multi-chunk books can join in a later rev), keep only texts containing
digits, ask the LLM to extract probe-worthy stated values. Output is a DRAFT file: nothing
becomes eval truth until Syed spot-checks a sample and promotes it (probes are generated by
the same model family being evaluated, unchecked, a hallucinated "expected" value would
poison the eval; the `quote` field exists so every probe is verifiable against its source
in seconds).

Provenance rides every probe: source doc id/title/url + judge score. Draft rows with
questions answerable WITHOUT the excerpt (general knowledge) are what the spot-check kills,
good probes test values the model could only know by retrieval or memorized calibration data
(the engine-grenade dimension).
"""
from __future__ import annotations

import json
import sqlite3
import time
from pathlib import Path
from typing import Callable

from . import llm
from .config import Config

SYSTEM = (
    "You extract exact-value quiz probes from automotive tuning reference text. A probe asks "
    "for ONE specific numeric value the excerpt explicitly states (a calibration constant, "
    "spec, threshold, table value, unit conversion). Only create probes whose answer is "
    "unambiguous in the excerpt. PREFER operational values a tuner acts on, AFR targets, "
    "injector flow/latency, duty cycles, sensor voltages/readings, temperatures, pressures, "
    "timing degrees, torque specs. AVOID definition-file structural trivia (table counts, "
    "memory addresses, file-format layout). If the excerpt states no probe-worthy numeric "
    "values, return an empty list."
)

_USER_TMPL = """Reference excerpt (title: {title}):

{text}

---
Write 0 to 3 exact-value probes from this excerpt. For each: a self-contained question a
Subaru tuner might ask (name the platform/part/table so it stands alone), the expected value
exactly as stated, its unit, and the verbatim sentence containing it."""

PROBE_SCHEMA = {
    "type": "object",
    "properties": {"probes": {"type": "array", "items": {
        "type": "object",
        "properties": {
            "question": {"type": "string"},
            "expected_value": {"type": "string"},   # verbatim number, e.g. "503.93"
            "unit": {"type": "string"},             # e.g. "cc/min"; "" if dimensionless
            "quote": {"type": "string"},            # the supporting sentence (spot-check aid)
        },
        "required": ["question", "expected_value", "unit", "quote"],
        "additionalProperties": False,
    }}},
    "required": ["probes"], "additionalProperties": False,
}


def candidate_docs(cfg: Config, limit: int) -> list[sqlite3.Row]:
    """Single-chunk reference keeps whose text contains digits.

    Ordering is a DETERMINISTIC HASH of the doc id (Knuth multiplicative), not id order:
    plain `ORDER BY id` sampled the first-ingested docs; all wiki/def files, and produced
    a probe draft with zero operational values (Syed's B2 catch, 2026-07-09). The hash
    scatters the sample across every source and ingestion era while staying reproducible.
    """
    conn = sqlite3.connect(f"file:{cfg.retrieval.db_path}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    return conn.execute(
        """SELECT d.id, d.title, d.url, d.source, d.text, j.score
           FROM document d JOIN judgment j ON j.doc_id = d.id
           WHERE d.tier='reference' AND j.score >= 4 AND j.n_chunks = 1
             AND d.gone_at IS NULL AND d.text GLOB '*[0-9]*'
           ORDER BY (d.id * 2654435761) % 4294967296 LIMIT ?""", (limit,)).fetchall()


def generate(cfg: Config, limit: int = 60, chat_fn: Callable | None = None,
             log=print) -> Path:
    chat_fn = chat_fn or llm.chat
    out = cfg.results_dir.parent / "data/e2_probes_draft.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    docs = candidate_docs(cfg, limit)
    n_probes = 0
    with out.open("w") as f:
        for i, d in enumerate(docs):
            text = d["text"][:12000]              # keep prompt+thinking inside 16k ctx
            try:
                content, usage, latency = chat_fn(
                    cfg.llm, SYSTEM,
                    _USER_TMPL.format(title=d["title"] or "untitled", text=text),
                    json_schema=PROBE_SCHEMA)
                probes = json.loads(content)["probes"] if content else []
            except (llm.LlmError, json.JSONDecodeError, KeyError) as e:
                log(f"  [{i+1}/{len(docs)}] doc {d['id']}: FAILED ({e}), skipping")
                continue
            for k, p in enumerate(probes):
                n_probes += 1
                f.write(json.dumps({
                    "probe_id": f"e2-{d['id']}-{k}", "generated_at": time.strftime("%F"),
                    **p,
                    "source": {"doc_id": d["id"], "title": d["title"], "url": d["url"],
                               "source": d["source"], "judge_score": d["score"]},
                    "generator_model": cfg.llm.model, "spot_checked": False,
                }) + "\n")
            f.flush()
            log(f"  [{i+1}/{len(docs)}] doc {d['id']}: +{len(probes)} probes ({latency:.0f}s)")
    log(f"draft: {n_probes} probes from {len(docs)} docs -> {out}")
    return out
